"""The sync waits for a repo the kit has not filled from its starter yet.

The kit's `bootstrap/create-repos.sh` makes each fleet repo with one README
that ends in a marker line; `bootstrap/copy-starter.sh` replaces that README
while it is unchanged, and refuses to overwrite any other file that differs
on the default branch. Step 10 merges `_agent-guidance` before steps 12 and
13 copy the registries and `wsl-automation`, so the sync's first runs reach
repos that still hold only that README. With the `guidance-sync` App's
`workflows: write` (acsi-kit PR #139) it could deliver there: AGENTS.md,
CLAUDE.md, the agent-checks workflow and the rest would land on the default
branch first, and copy-starter.sh would then refuse those files.

So `scripts/sync.sh` skips a repo, right after cloning it, while its README.md
still carries that marker line (counted as skipped, with a log line naming
the step that fills it), in a real run and a dry run alike. The marker is the
kit's own and never appears in the source owner's fleet, so their sync is
unchanged. `export/tests/test_unfilled_repos.py` holds the marker equal to
`bootstrap/lib/common.sh`'s GENERATED_README_MARKER, and a test in
`test/run-tests.sh` (GROUP_sync) runs the sync against one unfilled and one
filled repo.

Runs on the substituted tree.
"""

from __future__ import annotations

from pathlib import Path

MARKER = "<!-- generated by bootstrap/create-repos.sh; copy-starter.sh replaces this file while it is unchanged -->"

DECLARE = (
    'SELF_REPO="${SYNC_SELF_REPO:-_agent-guidance}"\n',
    'SELF_REPO="${SYNC_SELF_REPO:-_agent-guidance}"\n'
    "# The adoption kit's create-repos.sh ends each new repo's README.md with this\n"
    "# line, and copy-starter.sh replaces that README with the repo's starter. A\n"
    "# repo whose README still carries it has not been filled yet: see below.\n"
    f"KIT_UNFILLED_MARKER='{MARKER}'\n",
)

SKIP = (
    '    cd "$repo_dir"\n'
    "\n"
    "    # Configure git identity for commits (not inherited in fresh clones)\n",
    '    cd "$repo_dir"\n'
    "\n"
    "    # A repo the adoption kit created and has not filled from its starter yet\n"
    "    # (README.md is still the one create-repos.sh wrote). Delivering now would\n"
    "    # put files on its default branch that copy-starter.sh then refuses to\n"
    "    # overwrite, so the sync waits until the starter is merged.\n"
    '    if [[ -f README.md ]] && grep -qxF -- "$KIT_UNFILLED_MARKER" README.md; then\n'
    '        log "Not set up yet: README.md is still the one bootstrap/create-repos.sh wrote. Copy its starter with bootstrap/copy-starter.sh and merge it; the next sync delivers here. Skipping."\n'
    "        ((SKIP_COUNT++)) || true\n"
    '        cd "$REPO_ROOT"\n'
    "        continue\n"
    "    fi\n"
    "\n"
    "    # Configure git identity for commits (not inherited in fresh clones)\n",
)

LIST = (
    "                    failorg)\n",
    "                    kitorg)\n"
    "                        # test_sync_skips_unfilled_kit_repo's fixtures, off disk.\n"
    '                        rows=""\n'
    '                        for bare_dir in "${MOCK_BARE_DIR}"/kitorg_*; do\n'
    '                            [[ -d "$bare_dir" ]] || continue\n'
    '                            name=$(basename "$bare_dir")\n'
    '                            rows="${rows}${rows:+,}{\\"nameWithOwner\\":\\"kitorg/${name#kitorg_}\\"}"\n'
    "                        done\n"
    '                        json="[$rows]"\n'
    "                        ;;\n"
    "                    failorg)\n",
)

TEST = (
    "# ── Test: sync.sh retires the owner-only guidance files (ADR 0043) ──────────\n",
    "# ── Test (adoption kit): sync.sh waits for a repo its starter has not filled ──\n"
    "test_sync_skips_unfilled_kit_repo() {\n"
    '    echo ""\n'
    "    echo \"=== Test: sync.sh skips a repo whose README is still create-repos.sh's ===\"\n"
    f"    local marker='{MARKER}'\n"
    '    local bare="$TEST_DIR/kit-bare" work="$TEST_DIR/kit-work" out="$TEST_DIR/kit-sync"\n'
    '    local repos_yml="$TEST_DIR/repos-kit.yml" n w rc before after\n'
    '    rm -rf "$bare" "$work"\n'
    '    mkdir -p "$bare" "$work"\n'
    "    printf 'exclude: []\\n' > \"$repos_yml\"\n"
    "    for n in repo-unfilled repo-filled; do\n"
    '        w="$work/$n"\n'
    '        git init -q --bare --initial-branch=main "$bare/kitorg_$n"\n'
    '        git init -q --initial-branch=main "$w"\n'
    "        if [[ $n == repo-unfilled ]]; then\n"
    "            printf '# %s\\n\\nA repo.\\n\\n%s\\n' \"$n\" \"$marker\" > \"$w/README.md\"\n"
    "        else\n"
    "            printf '# %s\\n\\nFilled from its starter.\\n' \"$n\" > \"$w/README.md\"\n"
    "        fi\n"
    '        git -C "$w" add README.md\n'
    '        git -C "$w" -c user.name=test -c user.email=test@localhost -c commit.gpgsign=false commit -q -m init\n'
    '        git -C "$w" push -q "$bare/kitorg_$n" HEAD:main\n'
    "    done\n"
    "    run_kit_sync() {\n"
    "        GITHUB_REPOSITORY_OWNER=kitorg MOCK_BARE_DIR=\"$bare\" MOCK_PR_BODY_DIR=\"$TEST_DIR/kit-pr-bodies\" \\\n"
    "            REPOS_YML=\"$repos_yml\" PATH=\"$TEST_DIR/bin:$PATH\" \"$REPO_ROOT/scripts/sync.sh\" \"$@\"\n"
    "    }\n"
    '    before=$(git -C "$bare/kitorg_repo-unfilled" rev-parse main)\n'
    '    rc=0; run_kit_sync --dry-run > "$out-dry.log" 2>&1 || rc=$?\n'
    '    [[ $rc -eq 0 ]] && pass "unfilled kit repo (dry run): exits 0" || fail "unfilled kit repo (dry run): exits 0 (rc=$rc)"\n'
    '    repo_section "$out-dry.log" "=== kitorg/repo-unfilled ===" > "$out-dry-unfilled"\n'
    '    assert_contains "$out-dry-unfilled" "Not set up yet: README.md is still the one bootstrap/create-repos.sh wrote" \\\n'
    '        "unfilled kit repo (dry run): named as not set up yet"\n'
    '    assert_not_contains "$out-dry-unfilled" "[DRY RUN] Would" "unfilled kit repo (dry run): nothing offered"\n'
    '    rc=0; run_kit_sync > "$out.log" 2>&1 || rc=$?\n'
    '    [[ $rc -eq 0 ]] && pass "unfilled kit repo: the run exits 0" || fail "unfilled kit repo: the run exits 0 (rc=$rc)"\n'
    '    after=$(git -C "$bare/kitorg_repo-unfilled" rev-parse main)\n'
    '    [[ "$before" == "$after" ]] && pass "unfilled kit repo: its default branch did not move" \\\n'
    '        || fail "unfilled kit repo: its default branch did not move"\n'
    '    local refs\n'
    '    refs=$(git -C "$bare/kitorg_repo-unfilled" for-each-ref --format="%(refname)" refs/heads)\n'
    '    if grep -qvxF refs/heads/main <<<"$refs"; then\n'
    '        fail "unfilled kit repo: no branch was pushed either"\n'
    "    else\n"
    '        pass "unfilled kit repo: no branch was pushed either"\n'
    "    fi\n"
    '    assert_contains "$out.log" "1 synced, 1 skipped, 0 failed" "unfilled kit repo: counted as skipped, the filled one synced"\n'
    '    if git -C "$bare/kitorg_repo-filled" cat-file -e main:AGENTS.md 2>/dev/null; then\n'
    '        pass "unfilled kit repo: a filled repo beside it still gets AGENTS.md"\n'
    "    else\n"
    '        fail "unfilled kit repo: a filled repo beside it still gets AGENTS.md"\n'
    "    fi\n"
    "}\n"
    "\n"
    "# ── Test: sync.sh retires the owner-only guidance files (ADR 0043) ──────────\n",
)

GROUP = (
    "    test_sync_retire_owner_guidance\n)\n",
    "    test_sync_retire_owner_guidance\n    test_sync_skips_unfilled_kit_repo\n)\n",
)

EDITS = {
    "scripts/sync.sh": [DECLARE, SKIP],
    "test/run-tests.sh": [LIST, TEST, GROUP],
}


def apply(root: Path, ctx) -> None:
    for rel, edits in EDITS.items():
        path = root / rel
        text = path.read_text(encoding="utf-8")
        for old, new in edits:
            n = text.count(old)
            if n != 1:
                raise SystemExit(f"unfilled_repos: expected 1 occurrence in {rel}, found {n}: {old[:70]!r}")
            text = text.replace(old, new)
        path.write_text(text, encoding="utf-8")
